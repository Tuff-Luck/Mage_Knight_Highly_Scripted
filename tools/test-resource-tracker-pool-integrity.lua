-- Regression: generated Influence scoring, explicit Move/Psychic pool
-- reservations, and primary-target stability when split arrows are removed.
-- Run from repo root: lua5.2 tools/test-resource-tracker-pool-integrity.lua
local function read(path)
    local f=assert(io.open(path,"r"))
    local source=f:read("*a")
    f:close()
    return source
end
local function section(source,first,last)
    local a=assert(source:find(first,1,true),"Missing "..first)
    local b=assert(source:find(last,a+#first,true),"Missing "..last)
    return source:sub(a,b-1)
end
local reader=read("src/PlayingGame/PlayerBoard/CardRecognition.lua")
local arrows=read("src/PlayingGame/AttackAssignments.lua")
local trackerUI=read("src/PlayingGame/UI.lua")
-- Reputation and conquered-city Shields are conditional Interaction bonuses,
-- not independent Influence sources. A played Influence source (or a manual
-- offset representing one) is needed before either modifier becomes usable.
assert(trackerUI:find('local canModifyInfluence=not combat and base>0',1,true),
    "Interaction modifiers require positive Influence outside combat")
assert(trackerUI:find('showRow("InfluAmountPlain",influenceBase>0,34)',1,true)
    and trackerUI:find('joinLang({RESOURCE_TRACKER_FIELDS.InfluAmountPlain[3],influenceBase})',1,true),
    "The headline Influence row must exclude Interaction modifiers")
assert(trackerUI:find('refreshUnitOfferHighlights(interactionTotal)',1,true),
    "Unit affordability uses Interaction Influence, not Learning's ordinary pool")
assert(trackerUI:find('showRow("InfluAmountReput",canModifyInfluence and reputation~=0)',1,true),
    "Reputation must be hidden until Influence is available")
assert(trackerUI:find('showRow("InfluAmountCityS",canModifyInfluence and shields~=0 and reputation~=-99)',1,true),
    "Conquered-city Shields must be hidden until Influence is available")

-- Unplayed Reputation and Shields must never bias the default card resource choice.
local scoreEnv={
    gStates={resourceTracker={
        influence={generated=0,reputation=5,cityShields=2},
        move={move=0}}},
    resourceCardScanBySeat={[1]={cards={},totals={influence=0,move=4}}},
    resourceChoiceFamilies={"influence","move"},
    trackerPrivate={resourceTotalsKeyByField={
        influence={generated="influence"},move={move="move"}}}
}
setmetatable(scoreEnv,{__index=_G})
local scores=assert(load(section(reader,
    "local function trackerChoiceScores(guid,seatPos)",
    "-- First try to match a resource already contributed")..
    "\nreturn trackerChoiceScores","Choice scoring","t",scoreEnv))()
assert(scores("unused",1).influence==0,
    "Reputation and shields must not bias Influence option guesses")
assert(scores("unused",1).move==4,
    "Move generated by other cards must remain in the scores")
scoreEnv.gStates.resourceTracker.influence.generated=3
assert(scores("unused",1).influence==3,
    "Actual generated/manual Influence remains available to option scoring")

-- Two sources exist. One already has a manually chosen Cumbersome/Psychic
-- target and the second is free. Conversion must only offer the free pool.
local state={targets={moveA="enemy1",influenceA="enemy2"},
    explicit={moveA=true,influenceA=true}}
local cards={
    ["878d92"]={combatConversion="agility",resources={}},
    ["8c3de6"]={combatConversion="diplomacy",resources={}},
    moveA={resources={move=4}},
    moveB={resources={move=2}},
    influenceA={resources={influence=4}},
    influenceB={resources={influence=3}}}
local conversionEnv={
    combatConfig={conversionState={},hasPsychicAttack=function(guid)
        return guid=="enemy2"
    end},
    combatAssignmentState=state,
    resourceCardScanBySeat={[1]={cards=cards}},
    resourceCardsCombatTargetAcceptsMove=function(guid) return guid=="enemy1" end,
    resourceCardsMoveRole=function() return "combat" end
}
setmetatable(conversionEnv,{__index=_G})
assert(load(section(reader,
    "local function combatConversionReserved(key,amount,field)",
    "local function combatAssignmentSources(seat)"),
    "Conversion reservations","t",conversionEnv))()
local agility,available,active=conversionEnv.combatConfig.conversionFor(1,"agility")
assert(active and available==2,
    "Agility must not offer four points already assigned to Cumbersome")
agility.attack=2
local corrected=conversionEnv.combatConfig.conversionFor(1,"agility")
assert(corrected.attack==2,"Unassigned Move 2 must remain convertible")
state.explicit.moveA=nil
local _,freed=conversionEnv.combatConfig.conversionFor(1,"agility")
assert(freed==6,"Releasing the Move arrow must free the whole Move pool")

local diplomacy,payable,diplomacyOn=conversionEnv.combatConfig.conversionFor(1,"diplomacy")
assert(diplomacyOn and payable==3,
    "Diplomacy must not spend Influence already assigned as Psychic Block")
diplomacy.block=3
local saved=conversionEnv.combatConfig.conversionFor(1,"diplomacy")
assert(saved.block==3,"Unassigned Influence remains convertible")
state.targets.influenceA=nil
local _,allInfluence=conversionEnv.combatConfig.conversionFor(1,"diplomacy")
assert(allInfluence==7,"Clearing Psychic assignment must free Influence")
state.targets.influenceA="ordinaryEnemy"
local _,otherTarget=conversionEnv.combatConfig.conversionFor(1,"diplomacy")
assert(otherTarget==7,
    "Ordinary enemy targeting must not reserve an unrelated Influence pool")

-- Also test the actual source-consumption loop: its input order must never
-- let a reserved source be consumed before an unassigned one.
local consumeCode=section(reader,
    "local function consumeShared(field,amount)",
    "local function converted(guid,part,original,points,resourceCost)")
local consumeEnv={
    combatConversionReserved=function(key,amount,field)
        local target=state.targets[key]
        if state.explicit[key] and ((field=="move" and target=="enemy1")
            or (field=="influence" and target=="enemy2")) then
            return amount
        end
        return 0
    end
}
setmetatable(consumeEnv,{__index=_G})
local spend=assert(load([[
return function(sources,field,amount)
    local lateMoveSpent=0
]]..consumeCode..[[
    consumeShared(field,amount)
    return sources
end
]],"Shared source consumption","t",consumeEnv))()
state.targets.moveA="enemy1"
state.explicit.moveA=true
local sourceList={
    {key="moveA",move=4,resources={move=4},details={{key="move",amount=4}}},
    {key="moveB",move=2,resources={move=2},details={{key="move",amount=2}}}
}
spend(sourceList,"move",2)
assert(sourceList[1].move==4 and sourceList[2].move==0,
    "Converting free Move must leave the manually targeted Move unchanged")
state.targets.influenceA="enemy2"
sourceList={
    {key="influenceA",psychicInfluence=4,resources={influence=4},
        details={{key="influence",amount=4}}},
    {key="influenceB",psychicInfluence=3,resources={influence=3},
        details={{key="influence",amount=3}}}
}
spend(sourceList,"influence",3)
assert(sourceList[1].psychicInfluence==4
    and sourceList[2].psychicInfluence==0,
    "Converting free Influence must preserve the assigned Psychic pool")

-- Even when the physical scan changes record order, consuming free Move
-- must choose a consistent source rather than whichever pairs() visited first.
local unordered={
    {key="zFree",move=2,resources={move=2},details={{key="move",amount=2}}},
    {key="aFree",move=2,resources={move=2},details={{key="move",amount=2}}}
}
spend(unordered,"move",2)
assert(unordered[1].move==2 and unordered[2].move==0,
    "A rescan must consume the same unassigned source in key order")

-- Removing a secondary arrow must preserve the original primary. If the
-- primary disappears, the oldest remaining arrow becomes primary, regardless
-- of Lua pairs() enumeration order. Test duplicate arrows to one target too.
local registry={
    ["1"]={id="1",sourceGUID="move4",targetGUID="enemyA"},
    ["2"]={id="2",sourceGUID="move4",targetGUID="enemyB"},
    ["3"]={id="3",sourceGUID="move4",targetGUID="enemyC"}}
local combat={targets={move4="enemyA"},explicit={move4=true}}
local removals={}
local arrowEnv={
    assignmentRegistry=registry,gStates={attackAssignments={}},
    combatConfig={},
    resourceCardsCombatPrimaryTarget=function(key) return combat.targets[key] end,
    resourceCardsCombatForgetSource=function(key,replacement)
        removals[#removals+1]={key=key,target=replacement}
        combat.targets[key]=replacement
        combat.explicit[key]=replacement~=nil or nil
    end,
    refreshRenderedLines=function() end,
    resourceCardsSourceChanged=function() end
}
setmetatable(arrowEnv,{__index=_G})
local remove=assert(load(section(arrows,
    "local function persistAssignments()",
    "function attackAssignmentsBegin(")..
    "\nreturn removeAssignment","Arrow removal","t",arrowEnv))()
remove("2")
assert(combat.targets.move4=="enemyA" and #removals==0
    and #arrowEnv.gStates.attackAssignments==2,
    "Deleting a secondary arrow must not change the primary")
remove("1")
assert(combat.targets.move4=="enemyC" and combat.explicit.move4,
    "Deleting the primary must promote its oldest remaining arrow")
remove("3")
assert(combat.targets.move4==nil and combat.explicit.move4==nil,
    "Deleting the final arrow must clear its calculator allocation")
registry["4"]={id="4",sourceGUID="move4",targetGUID="enemyA"}
registry["5"]={id="5",sourceGUID="move4",targetGUID="enemyA"}
registry["6"]={id="6",sourceGUID="move4",targetGUID="enemyC"}
combat.targets.move4="enemyA"
combat.explicit.move4=true
remove("4")
assert(combat.targets.move4=="enemyA",
    "Removing one duplicate primary arrow must retain the other")
remove("5")
assert(combat.targets.move4=="enemyC",
    "The final primary arrow must promote another saved target")

print("Resource scoring, conversion reservations and split-arrow integrity passed")
